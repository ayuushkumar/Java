package practiceQuestions;

public class Ques6 {
    public static void main(String[] args) {

//==========================================================
// Try increment and decrement operator on a java program.
//==========================================================

        int i = 6;
        System.out.println(i++); // Prints 6 becomes 7
        System.out.println(i--); // 7 --> 6
        System.out.println(--i); // 5
        System.out.println(++i); // 6
        int j = 7;
        System.out.println(j++); // Prints 7 becomes 8
        System.out.println(j--); // 8 --> 7
        System.out.println(--j); // 6
        System.out.println(++j); // 7
    }
}
