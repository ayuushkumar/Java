package javaCoding;

public class J2_literals {
    public static void main(String[] args) {
        byte a = 127; //1byte,8bits
        System.out.println(a);

        short s = 100; //2byt,16bits
        System.out.println(s);

        int b = 10000; //4byte,32bits
        System.out.println(b);

        long l = 2000000000000L; //8byte,64bits
        System.out.println(l);

        char c = 'A'; //2byte,16bits
        System.out.println(c);

        float f = 3.14f; //4byte,32bits
        System.out.println(f);

        double d = 1.23d; //8byte,64 bits
        System.out.println(d);

        boolean bool = true; //true or false
        System.out.println(bool);

        String str = "Hello World";
        System.out.println(str);

    }
}
